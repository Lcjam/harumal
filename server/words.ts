function isUsable(word: string): boolean {
  try {
    validateChallengeWord(word);
    return true;
  } catch {
    return false;
  }
}

const rejected = CATALOG.filter((word) => !isUsable(word));
if (rejected.length) {
  console.error(JSON.stringify({ level: "error", event: "solo_word_rejected", words: rejected }));
}

/** 오늘의 단어와 연습 모드가 정답으로 고르는 단어입니다. */
export const SOLO_WORDS: readonly string[] = CATALOG.filter(isUsable);

/** 검증 테스트에서만 쓰는 원본 목록입니다. */
export const SOLO_WORD_CATALOG = CATALOG;

/**
 * 자모로 풀어 쓴 형태에서 허용 단어를 찾습니다.
 * 화면 키보드는 자모를 그대로 보내고, 채점도 자모 단위라 이 색인이면 충분합니다.
 * 자모 배열이 같은 단어끼리는(무거/묵어 같은 경우) 결과가 어차피 같습니다.
 *
 * 정답 후보보다 넓은 목록을 쓰는 이유는, 맞는 낱말을 넣었는데 "사전에 없다"고
 * 막히는 일이 게임에서 가장 답답하기 때문입니다.
 */
const BY_JAMO = new Map<string, string>();
for (const word of ALLOWED_GUESS_WORDS) {
  if (!isUsable(word)) continue;
  const key = decomposeHangul(word).join("");
  if (!BY_JAMO.has(key)) BY_JAMO.set(key, word);
}

/** 추측과 출제에 쓸 수 있는 낱말 수입니다. */
export const ALLOWED_WORD_COUNT = BY_JAMO.size;

export function isDictionaryWord(word: string): boolean {
  return BY_JAMO.has(decomposeHangul(word).join(""));
}

/** 사전에 있으면 완성된 단어 형태로 돌려줍니다. 자모로 입력해도 기록은 단어로 남습니다. */
export function findDictionaryWord(input: string): string | undefined {
  return BY_JAMO.get(decomposeHangul(input).join(""));
}
